GLYPH = {k: np.array([[c == '1' for c in r] for r in v.split()], bool) for k, v in _G.items()}

def text_mask(s, scale=1, adv=6):
    s = s.upper()
    m = np.zeros((7 * scale, max(1, len(s) * adv * scale)), bool)
    for i, ch in enumerate(s):
        g = GLYPH.get(ch, GLYPH['?'])
        g = np.kron(g, np.ones((scale, scale), bool))
        m[:, i * adv * scale:i * adv * scale + 5 * scale] |= g
    return m

def blit_mask(img, mask, x, y, col):
    H, W = img.shape; h, w = mask.shape
    x0, y0 = max(0, x), max(0, y); x1, y1 = min(W, x + w), min(H, y + h)
    if x1 <= x0 or y1 <= y0: return
    sub = mask[y0 - y:y1 - y, x0 - x:x1 - x]
    img[y0:y1, x0:x1][sub] = col

def blit_sprite(img, spr, x, y):
    """spr: int array, -1 = transparent"""
    H, W = img.shape; h, w = spr.shape
    x0, y0 = max(0, x), max(0, y); x1, y1 = min(W, x + w), min(H, y + h)
    if x1 <= x0 or y1 <= y0: return
    sub = spr[y0 - y:y1 - y, x0 - x:x1 - x]
    reg = img[y0:y1, x0:x1]; m = sub >= 0; reg[m] = sub[m]

def sprite(rows, cmap):
    return np.array([[cmap.get(c, -1) for c in r] for r in rows], int)
